export function getLifestyleCategory(slug: string) {
  return lifestyleCategories.find((category) => category.slug === slug);
}

export function isSubscriptionCategory(categorySlug: string) {
  return getLifestyleCategory(categorySlug)?.access === "subscription";
}

export function getCategoryArticles(categorySlug: LifestyleCategorySlug) {
  return lifestyleArticles.filter((article) => article.categorySlug === categorySlug);
}

export function getLifestyleArticle(categorySlug: string, articleSlug: string) {
  return lifestyleArticles.find(
    (article) => article.categorySlug === categorySlug && article.slug === articleSlug,
  );
}

export function getPublishedArticles(categorySlug?: LifestyleCategorySlug) {
  return lifestyleArticles.filter(
    (article) => article.status === "published" && (!categorySlug || article.categorySlug === categorySlug),
  );
}

export function getCategoryAvailability(categorySlug: LifestyleCategorySlug) {
  return `${getCategoryArticles(categorySlug).length} articole`;
}
